DACUTE = ["..#..#..", ".#..#..."]
ACUTE_U = ["....#...", "...#...."]


def accented(code, base, accent, upper):
    src = G[ord(base)]
    full = list(src)
    if upper:
        full[0], full[1] = accent[0], accent[1]
    else:
        full[2], full[3] = accent[0], accent[1]
    G[code] = full


