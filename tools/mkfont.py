def main():
    lines = ["/* GENERALT FAJL - tools/mkfont.py. 8x16 bitmap font, ISO-8859-2 reszhalmaz. */",
             '#include "font.h"', "", "const u8 font8x16[256][16] = {"]
    for code in range(256):
        rows = G.get(code, ["........"] * 16)
        vals = []
        for r in rows:
            v = 0
            for i, c in enumerate(r):
                if c == '#':
                    v |= 0x80 >> i
            vals.append(f"0x{v:02X}")
        name = chr(code) if 32 <= code < 127 else ""
        lines.append(f"    [0x{code:02X}] = {{ {', '.join(vals)} }}, /* {name} */")
    lines.append("};")
    lines.append("")
    with open(OUT, "w", newline="\n") as f:
        f.write("\n".join(lines))
    print(f"{OUT}: {len(G)} glyph")


if __name__ == "__main__":
    main()
